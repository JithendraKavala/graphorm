package com.graphorm.core.metadata;

import java.util.Objects;

/**
 * Immutable metadata record representing a scalar field, calculated expression,
 * aggregation, or relational field on an entity.
 *
 * @param name              the logical field name in the schema
 * @param javaType          the Java class type of this field (may be null if typeName is set)
 * @param typeName          the string representation of the field's type
 * @param dbColumnName      the mapped physical column name or expression in the database
 * @param isPrimaryKey      whether this field is part of the primary key
 * @param isNullable        whether this field permits null values
 * @param isUnique          whether this field has a unique constraint
 * @param isGenerated       whether this field's value is generated by the database
 * @param defaultValue      the default value literal or function expression (e.g. "autoincrement()")
 * @param isAggregate       whether this field represents an aggregation in a view model
 * @param aggregateFunction the aggregation function name (e.g. "COUNT", "SUM", "AVG")
 * @param expression        the raw SQL/computed expression if this is an expression field
 * @param isRelation        whether this field is a navigation relation field
 * @param relationName      the associated relation name if isRelation is true
 */
public record FieldMetadata(
        String name,
        Class<?> javaType,
        String typeName,
        String dbColumnName,
        boolean isPrimaryKey,
        boolean isNullable,
        boolean isUnique,
        boolean isGenerated,
        String defaultValue,
        boolean isAggregate,
        String aggregateFunction,
        String expression,
        boolean isRelation,
        String relationName
) {

    /**
     * Compact constructor enforcing immutability and argument validation.
     */
    public FieldMetadata {
        Objects.requireNonNull(name, "Field name must not be null");
        if (name.isBlank()) {
            throw new IllegalArgumentException("Field name must not be blank");
        }
        if (dbColumnName == null || dbColumnName.isBlank()) {
            dbColumnName = name;
        }
        if (typeName == null || typeName.isBlank()) {
            typeName = javaType != null ? javaType.getSimpleName() : "Object";
        }
    }

    /**
     * Standard constructor matching the core specification.
     *
     * @param name         field name
     * @param javaType     Java class type
     * @param dbColumnName mapped database column name
     * @param isPrimaryKey primary key flag
     * @param isNullable   nullability flag
     * @param isUnique     uniqueness flag
     * @param isGenerated  database-generated flag
     * @param defaultValue default value literal or expression
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue
    ) {
        this(
                name,
                javaType,
                javaType != null ? javaType.getSimpleName() : "Object",
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                false,
                null,
                null,
                false,
                null
        );
    }

    /**
     * Creates a new builder for {@link FieldMetadata}.
     *
     * @param name the logical field name
     * @return a new Builder instance
     */
    public static Builder builder(String name) {
        return new Builder(name);
    }

    /**
     * Creates a new builder for {@link FieldMetadata} with a name and Java type.
     *
     * @param name     the logical field name
     * @param javaType the Java class type
     * @return a new Builder instance
     */
    public static Builder builder(String name, Class<?> javaType) {
        return new Builder(name).javaType(javaType);
    }

    /**
     * Fluent builder for {@link FieldMetadata}.
     */
    public static final class Builder {
        private final String name;
        private Class<?> javaType;
        private String typeName;
        private String dbColumnName;
        private boolean isPrimaryKey;
        private boolean isNullable;
        private boolean isUnique;
        private boolean isGenerated;
        private String defaultValue;
        private boolean isAggregate;
        private String aggregateFunction;
        private String expression;
        private boolean isRelation;
        private String relationName;

        private Builder(String name) {
            this.name = Objects.requireNonNull(name, "Field name must not be null");
        }

        public Builder javaType(Class<?> javaType) {
            this.javaType = javaType;
            return this;
        }

        public Builder typeName(String typeName) {
            this.typeName = typeName;
            return this;
        }

        public Builder dbColumnName(String dbColumnName) {
            this.dbColumnName = dbColumnName;
            return this;
        }

        public Builder primaryKey(boolean isPrimaryKey) {
            this.isPrimaryKey = isPrimaryKey;
            return this;
        }

        public Builder nullable(boolean isNullable) {
            this.isNullable = isNullable;
            return this;
        }

        public Builder unique(boolean isUnique) {
            this.isUnique = isUnique;
            return this;
        }

        public Builder generated(boolean isGenerated) {
            this.isGenerated = isGenerated;
            return this;
        }

        public Builder defaultValue(String defaultValue) {
            this.defaultValue = defaultValue;
            return this;
        }

        public Builder aggregate(String aggregateFunction) {
            this.isAggregate = true;
            this.aggregateFunction = aggregateFunction;
            return this;
        }

        public Builder expression(String expression) {
            this.expression = expression;
            return this;
        }

        public Builder relation(String relationName) {
            this.isRelation = true;
            this.relationName = relationName;
            return this;
        }

        public FieldMetadata build() {
            return new FieldMetadata(
                    name,
                    javaType,
                    typeName,
                    dbColumnName,
                    isPrimaryKey,
                    isNullable,
                    isUnique,
                    isGenerated,
                    defaultValue,
                    isAggregate,
                    aggregateFunction,
                    expression,
                    isRelation,
                    relationName
            );
        }
    }
}
