package com.graphorm.core.metadata;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Objects;

/**
 * Immutable metadata record representing a scalar field, calculated expression,
 * aggregation, relational field, backend-injected field, optimistic lock version,
 * or multi-tenant partition key on an entity.
 *
 * @param name              the logical field name in the schema
 * @param javaType          the Java class type of this field (may be null if typeName is set)
 * @param typeName          the string representation of the field's type
 * @param dbColumnName      the mapped physical column name or expression in the database
 * @param isPrimaryKey      whether this field is part of the primary key
 * @param isNullable        whether this field permits null values
 * @param isUnique          whether this field has a unique constraint
 * @param isGenerated       whether this field's value is generated by the database
 * @param defaultValue      the default value literal or function expression (e.g. "autoincrement()")
 * @param isAggregate       whether this field represents an aggregation in a view model
 * @param aggregateFunction the aggregation function name (e.g. "COUNT", "SUM", "AVG")
 * @param expression        the raw SQL/computed expression if this is an expression field
 * @param isRelation        whether this field is a navigation relation field
 * @param relationName      the associated relation name if isRelation is true
 * @param authRoles         the required security roles defined via {@code @auth(roles: [...])}
 * @param isInjected        whether this field is backend-injected from security or execution context (via @injected)
 * @param injectedFrom      the context source key or provider identifier (e.g. "tenantId", "auth.username", "auth.role")
 * @param isVersion         whether this field is used for optimistic locking concurrency control (via @version)
 * @param isTenantId        whether this field is a multi-tenant isolation key (via @tenantId)
 */
public record FieldMetadata(
        String name,
        Class<?> javaType,
        String typeName,
        String dbColumnName,
        boolean isPrimaryKey,
        boolean isNullable,
        boolean isUnique,
        boolean isGenerated,
        String defaultValue,
        boolean isAggregate,
        String aggregateFunction,
        String expression,
        boolean isRelation,
        String relationName,
        List<String> authRoles,
        boolean isInjected,
        String injectedFrom,
        boolean isVersion,
        boolean isTenantId
) {

    /**
     * Compact constructor enforcing immutability and argument validation.
     */
    public FieldMetadata {
        Objects.requireNonNull(name, "Field name must not be null");
        if (name.isBlank()) {
            throw new IllegalArgumentException("Field name must not be blank");
        }
        if (dbColumnName == null || dbColumnName.isBlank()) {
            dbColumnName = name;
        }
        if (typeName == null || typeName.isBlank()) {
            typeName = javaType != null ? javaType.getSimpleName() : "Object";
        }
        authRoles = authRoles == null ? List.of() : List.copyOf(authRoles);
        if (injectedFrom != null && injectedFrom.isBlank()) {
            injectedFrom = null;
        }
        if (injectedFrom != null) {
            isInjected = true;
        }
    }

    /**
     * Backward-compatible constructor without isTenantId.
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String typeName,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue,
            boolean isAggregate,
            String aggregateFunction,
            String expression,
            boolean isRelation,
            String relationName,
            List<String> authRoles,
            boolean isInjected,
            String injectedFrom,
            boolean isVersion
    ) {
        this(
                name,
                javaType,
                typeName,
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                isAggregate,
                aggregateFunction,
                expression,
                isRelation,
                relationName,
                authRoles,
                isInjected,
                injectedFrom,
                isVersion,
                false
        );
    }

    /**
     * Backward-compatible constructor without isVersion and isTenantId.
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String typeName,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue,
            boolean isAggregate,
            String aggregateFunction,
            String expression,
            boolean isRelation,
            String relationName,
            List<String> authRoles,
            boolean isInjected,
            String injectedFrom
    ) {
        this(
                name,
                javaType,
                typeName,
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                isAggregate,
                aggregateFunction,
                expression,
                isRelation,
                relationName,
                authRoles,
                isInjected,
                injectedFrom,
                false,
                false
        );
    }

    /**
     * Backward-compatible constructor without isInjected, injectedFrom, isVersion, and isTenantId.
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String typeName,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue,
            boolean isAggregate,
            String aggregateFunction,
            String expression,
            boolean isRelation,
            String relationName,
            List<String> authRoles
    ) {
        this(
                name,
                javaType,
                typeName,
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                isAggregate,
                aggregateFunction,
                expression,
                isRelation,
                relationName,
                authRoles,
                false,
                null,
                false,
                false
        );
    }

    /**
     * Constructor without explicit authRoles and injection flags for backward compatibility.
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String typeName,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue,
            boolean isAggregate,
            String aggregateFunction,
            String expression,
            boolean isRelation,
            String relationName
    ) {
        this(
                name,
                javaType,
                typeName,
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                isAggregate,
                aggregateFunction,
                expression,
                isRelation,
                relationName,
                List.of(),
                false,
                null,
                false,
                false
        );
    }

    /**
     * Standard constructor matching the core specification.
     */
    public FieldMetadata(
            String name,
            Class<?> javaType,
            String dbColumnName,
            boolean isPrimaryKey,
            boolean isNullable,
            boolean isUnique,
            boolean isGenerated,
            String defaultValue
    ) {
        this(
                name,
                javaType,
                javaType != null ? javaType.getSimpleName() : "Object",
                dbColumnName,
                isPrimaryKey,
                isNullable,
                isUnique,
                isGenerated,
                defaultValue,
                false,
                null,
                null,
                false,
                null,
                List.of(),
                false,
                null,
                false,
                false
        );
    }

    /**
     * Indicates whether this field has required security roles defined.
     */
    public boolean hasAuthRoles() {
        return authRoles != null && !authRoles.isEmpty();
    }

    /**
     * Checks whether the specified user roles satisfy this field's required roles.
     */
    public boolean isAuthorized(Collection<String> userRoles) {
        if (!hasAuthRoles()) {
            return true;
        }
        if (userRoles == null || userRoles.isEmpty()) {
            return false;
        }
        for (String req : authRoles) {
            String cleanReq = req.toUpperCase();
            if (cleanReq.startsWith("ROLE_")) {
                cleanReq = cleanReq.substring(5);
            }
            for (String userRole : userRoles) {
                if (userRole == null) {
                    continue;
                }
                String cleanUser = userRole.toUpperCase();
                if (cleanUser.startsWith("ROLE_")) {
                    cleanUser = cleanUser.substring(5);
                }
                if (cleanReq.equals(cleanUser)) {
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * Creates a new builder for {@link FieldMetadata}.
     */
    public static Builder builder(String name) {
        return new Builder(name);
    }

    /**
     * Creates a new builder for {@link FieldMetadata} with a name and Java type.
     */
    public static Builder builder(String name, Class<?> javaType) {
        return new Builder(name).javaType(javaType);
    }

    /**
     * Fluent builder for {@link FieldMetadata}.
     */
    public static final class Builder {
        private final String name;
        private Class<?> javaType;
        private String typeName;
        private String dbColumnName;
        private boolean isPrimaryKey;
        private boolean isNullable;
        private boolean isUnique;
        private boolean isGenerated;
        private String defaultValue;
        private boolean isAggregate;
        private String aggregateFunction;
        private String expression;
        private boolean isRelation;
        private String relationName;
        private final List<String> authRoles = new ArrayList<>();
        private boolean isInjected;
        private String injectedFrom;
        private boolean isVersion;
        private boolean isTenantId;

        private Builder(String name) {
            this.name = Objects.requireNonNull(name, "Field name must not be null");
        }

        public Builder javaType(Class<?> javaType) {
            this.javaType = javaType;
            return this;
        }

        public Builder typeName(String typeName) {
            this.typeName = typeName;
            return this;
        }

        public Builder dbColumnName(String dbColumnName) {
            this.dbColumnName = dbColumnName;
            return this;
        }

        public Builder primaryKey(boolean isPrimaryKey) {
            this.isPrimaryKey = isPrimaryKey;
            return this;
        }

        public Builder nullable(boolean isNullable) {
            this.isNullable = isNullable;
            return this;
        }

        public Builder unique(boolean isUnique) {
            this.isUnique = isUnique;
            return this;
        }

        public Builder generated(boolean isGenerated) {
            this.isGenerated = isGenerated;
            return this;
        }

        public Builder defaultValue(String defaultValue) {
            this.defaultValue = defaultValue;
            return this;
        }

        public Builder aggregate(String aggregateFunction) {
            this.isAggregate = true;
            this.aggregateFunction = aggregateFunction;
            return this;
        }

        public Builder expression(String expression) {
            this.expression = expression;
            return this;
        }

        public Builder relation(String relationName) {
            this.isRelation = true;
            this.relationName = relationName;
            return this;
        }

        public Builder authRoles(List<String> roles) {
            this.authRoles.clear();
            if (roles != null) {
                this.authRoles.addAll(roles);
            }
            return this;
        }

        public Builder authRoles(String... roles) {
            this.authRoles.clear();
            if (roles != null) {
                for (String r : roles) {
                    if (r != null && !r.isBlank()) {
                        this.authRoles.add(r.trim());
                    }
                }
            }
            return this;
        }

        public Builder addAuthRole(String role) {
            if (role != null && !role.isBlank()) {
                this.authRoles.add(role.trim());
            }
            return this;
        }

        public Builder injected(String injectedFrom) {
            this.isInjected = true;
            this.injectedFrom = injectedFrom;
            return this;
        }

        public Builder injected(boolean isInjected, String injectedFrom) {
            this.isInjected = isInjected;
            this.injectedFrom = injectedFrom;
            return this;
        }

        public Builder version(boolean isVersion) {
            this.isVersion = isVersion;
            return this;
        }

        public Builder version() {
            this.isVersion = true;
            return this;
        }

        public Builder tenantId(boolean isTenantId) {
            this.isTenantId = isTenantId;
            return this;
        }

        public Builder tenantId() {
            this.isTenantId = true;
            return this;
        }

        public FieldMetadata build() {
            return new FieldMetadata(
                    name,
                    javaType,
                    typeName,
                    dbColumnName,
                    isPrimaryKey,
                    isNullable,
                    isUnique,
                    isGenerated,
                    defaultValue,
                    isAggregate,
                    aggregateFunction,
                    expression,
                    isRelation,
                    relationName,
                    List.copyOf(authRoles),
                    isInjected,
                    injectedFrom,
                    isVersion,
                    isTenantId
            );
        }
    }
}
